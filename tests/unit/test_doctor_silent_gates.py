"""doctor names a commit gate that is set up and never judges anything.

Two setups passed every commit without a word:

- Route 1 writes crapkit's hook to .git/hooks/pre-commit. A core.hooksPath set
  anywhere else (a global one, husky's .husky/_) sends git to another
  directory, and git runs no hook from .git/hooks at all.
- Route 3 names crapkit-gate in .pre-commit-config.yaml, and nothing ran
  `pre-commit install`.

WARN, never FAIL: the commit still succeeds; it just was not gated. CI's
`pre-commit run --all-files` is no such setup: outside a commit, with nothing
staged, the hook judges every tracked file, so doctor says nothing about it.
"""
from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from crapkit.cli import admin
from crapkit.doctor import GateHook, HookRoute, skipped_gates

ROUTE_1 = "#!/bin/sh\nexec python -m crapkit hook-precommit\n"
GATE_CONFIG = ("repos:\n  - repo: https://github.com/JeanFrancoisGagne/crapkit\n    rev: v0.8.0\n"
               "    hooks:\n      - id: crapkit-gate\n")
# The file `pre-commit install` writes, cut to the line that runs the framework.
FRAMEWORK_HOOK = ("#!/usr/bin/env bash\n# File generated by pre-commit\n"
                  "exec pre-commit hook-impl --hook-type=pre-commit\n")
LOCAL_HOOK = GateHook("/r/.git/hooks/pre-commit", ROUTE_1,
                      "git config --local core.hooksPath /r/.git/hooks")
COMMITTED_HOOK = GateHook("githooks/pre-commit", ROUTE_1, "git config core.hooksPath githooks")


def route(**changes) -> HookRoute:
    base = dict(effective="/home/u/.githooks/pre-commit", effective_text="",
                edit="/home/u/.githooks/pre-commit", scope="global", value="/home/u/.githooks")
    return HookRoute(**{**base, **changes})


UNSET = dict(effective=".git/hooks/pre-commit", edit=".git/hooks/pre-commit", scope="", value="")


# --- the hook git is sent away from ---------------------------------------------

def test_a_crapkit_hook_git_never_runs_is_one_warn_naming_both_paths_and_both_fixes():
    (finding,) = skipped_gates(route(), (LOCAL_HOOK,), framework=False)

    assert finding.level == "WARN"
    assert finding.text == (
        "/r/.git/hooks/pre-commit runs crapkit's gate, but core.hooksPath (global config: "
        "/home/u/.githooks) sends git to /home/u/.githooks/pre-commit, so every commit here "
        "skips the gate without a word; run `git config --local core.hooksPath "
        "/r/.git/hooks` in this repo, or call crapkit hook-precommit from "
        "/home/u/.githooks/pre-commit")


def test_a_committed_hook_a_clone_never_pointed_git_at_names_route_2_s_config_line():
    """Route 2 commits githooks/pre-commit and asks every clone to run one git
    config line. A clone that skipped it commits breaches with no gate."""
    (finding,) = skipped_gates(route(**UNSET), (COMMITTED_HOOK,), framework=False)

    assert finding.text == (
        "githooks/pre-commit runs crapkit's gate, but core.hooksPath is unset and git runs "
        ".git/hooks/pre-commit, so every commit here skips the gate without a word; run "
        "`git config core.hooksPath githooks` in this repo, or call crapkit hook-precommit "
        "from .git/hooks/pre-commit")


def test_husky_taking_the_hooks_path_back_names_the_file_a_user_edits():
    """husky 9 sets core.hooksPath to .husky/_ on every npm install, and its
    stub there runs .husky/pre-commit, which is where a gate line goes."""
    husky = route(effective=".husky/_/pre-commit", effective_text='. "$(dirname "$0")/h"\nnpm test\n',
                  edit=".husky/pre-commit", scope="local", value=".husky/_")

    (finding,) = skipped_gates(husky, (COMMITTED_HOOK,), framework=False)

    assert "core.hooksPath (local config: .husky/_) sends git to .husky/_/pre-commit" in finding.text
    assert finding.text.endswith("or call crapkit hook-precommit from .husky/pre-commit")


@pytest.mark.parametrize("changes, hooks", [
    ({**UNSET, "effective_text": ROUTE_1}, (LOCAL_HOOK,)),
    ({"effective_text": "#!/bin/sh\nnpx lint-staged\ncrapkit hook-precommit\n"}, (LOCAL_HOOK,)),
    ({}, ()),
    ({}, (LOCAL_HOOK._replace(text=""),)),
    ({}, (LOCAL_HOOK._replace(text="#!/bin/sh\nnpx lint-staged\n"),)),
], ids=["git-runs-it", "hooks-path-calls-crapkit", "no-gate-hook", "empty-hook", "hook-not-crapkit"])
def test_a_hook_git_does_run_or_one_that_is_not_crapkit_says_nothing(changes, hooks):
    assert skipped_gates(route(**changes), hooks, framework=False) == ()


def test_two_skipped_gate_hooks_are_one_warn_each():
    found = skipped_gates(route(), (LOCAL_HOOK, COMMITTED_HOOK), framework=False)

    assert [f.text.split()[0] for f in found] == ["/r/.git/hooks/pre-commit", "githooks/pre-commit"]


# --- Route 3 installed nowhere ------------------------------------------------------

def test_a_pre_commit_config_naming_the_gate_with_no_framework_hook_says_run_install():
    (finding,) = skipped_gates(route(**UNSET), (), framework=True)

    assert finding.text == (
        ".pre-commit-config.yaml names crapkit-gate, but core.hooksPath is unset and git runs "
        ".git/hooks/pre-commit, which pre-commit did not write, so every commit here skips the "
        "gate without a word; run `pre-commit install` in this repo")


def test_under_a_hooks_path_the_framework_line_names_the_file_to_call_crapkit_from():
    (finding,) = skipped_gates(route(), (), framework=True)

    assert finding.text.endswith(
        "`pre-commit install` refuses while core.hooksPath is set, so call crapkit "
        "hook-precommit from /home/u/.githooks/pre-commit")


@pytest.mark.parametrize("text", [FRAMEWORK_HOOK, "#!/bin/sh\nexec pre-commit run\n",
                                  "#!/bin/sh\nexec prek run\n"])
def test_a_framework_hook_git_runs_is_the_gate(text):
    assert skipped_gates(route(effective_text=text), (), framework=True) == ()


def test_the_framework_s_own_hook_shadowed_by_a_global_path_is_a_skipped_gate():
    installed = LOCAL_HOOK._replace(text=FRAMEWORK_HOOK)

    (finding,) = skipped_gates(route(), (installed,), framework=True)

    assert finding.text.startswith("/r/.git/hooks/pre-commit runs crapkit's gate, but core.hooksPath")


def test_a_framework_hook_without_the_gate_in_its_config_is_not_a_gate():
    installed = LOCAL_HOOK._replace(text=FRAMEWORK_HOOK)

    assert skipped_gates(route(), (installed,), framework=False) == ()


