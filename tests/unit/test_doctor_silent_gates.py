# --- through git ------------------------------------------------------------------

def _git(root: Path, *args: str, env: dict | None = None) -> str:
    return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True, text=True,
                          env=env).stdout.strip()


@pytest.fixture
def repo(tmp_path, monkeypatch):
    """A repo with Route 1 written, and a global git config this test owns."""
    home = tmp_path / "home"
    home.mkdir()
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", str(home / ".gitconfig"))
    monkeypatch.setenv("GIT_CONFIG_NOSYSTEM", "1")
    root = tmp_path / "repo"
    root.mkdir()
    _git(root, "init", "-q")
    hook = root / ".git" / "hooks" / "pre-commit"
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(ROUTE_1, encoding="utf-8")
    return root


def test_route_1_under_a_global_hooks_path_warns_and_the_named_fix_clears_it(repo, tmp_path):
    global_hooks = tmp_path / "home" / ".githooks"
    global_hooks.mkdir()
    _git(repo, "config", "--global", "core.hooksPath", global_hooks.as_posix())

    (finding,) = admin._doctor_silent_gates(repo)
    assert "(global config: " in finding.text
    assert f"sends git to {(global_hooks / 'pre-commit').resolve().as_posix()}" in finding.text

    fix = finding.text.split("`")[1]
    _git(repo, *fix.split()[1:])
    assert admin._doctor_silent_gates(repo) == []
    assert Path(_git(repo, "rev-parse", "--path-format=absolute", "--git-path",
                     "hooks/pre-commit")).resolve() == (repo / ".git/hooks/pre-commit").resolve()


def test_route_1_with_no_hooks_path_says_nothing(repo):
    assert admin._doctor_silent_gates(repo) == []


def test_pre_commit_in_a_workflow_over_the_gate_says_nothing(repo):
    """The CI run judges every tracked file, so it is a gate, not a silent one."""
    (repo / ".pre-commit-config.yaml").write_text(GATE_CONFIG, encoding="utf-8")
    workflows = repo / ".github" / "workflows"
    workflows.mkdir(parents=True)
    (workflows / "lint.yaml").write_text("steps:\n  - run: pre-commit run --all-files\n",
                                         encoding="utf-8")

    assert admin._doctor_silent_gates(repo) == []


def test_outside_a_repository_nothing_is_read(tmp_path):
    assert admin._doctor_silent_gates(tmp_path) == []


def _isolated_git(tmp_path: Path, monkeypatch) -> None:
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", str(tmp_path / ".gitconfig"))
    monkeypatch.setenv("GIT_CONFIG_NOSYSTEM", "1")


def test_a_clone_that_skipped_route_2_s_config_line_warns_and_the_named_fix_clears_it(tmp_path,
                                                                                     monkeypatch):
    _isolated_git(tmp_path, monkeypatch)
    root = tmp_path / "clone"
    (root / "githooks").mkdir(parents=True)
    _git(root, "init", "-q")
    (root / "githooks" / "pre-commit").write_text(ROUTE_1, encoding="utf-8")
    _git(root, "add", "githooks/pre-commit")

    (finding,) = admin._doctor_silent_gates(root)
    assert finding.text.startswith("githooks/pre-commit runs crapkit's gate, but core.hooksPath "
                                   "is unset and git runs .git/hooks/pre-commit")

    fix = finding.text.split("`")[1]
    assert fix == "git config core.hooksPath githooks"
    _git(root, *fix.split()[1:])
    assert admin._doctor_silent_gates(root) == []


def test_a_committed_gate_below_the_crapkit_root_s_repo_top_is_found_from_the_root(tmp_path,
                                                                                  monkeypatch):
    """A crapkit root below the git top still reads the hooks the top commits."""
    _isolated_git(tmp_path, monkeypatch)
    top = tmp_path / "mono"
    (top / "tools" / "githooks").mkdir(parents=True)
    (top / "packages" / "api").mkdir(parents=True)
    _git(top, "init", "-q")
    (top / "tools" / "githooks" / "pre-commit").write_text(ROUTE_1, encoding="utf-8")
    _git(top, "add", "tools/githooks/pre-commit")

    (finding,) = admin._doctor_silent_gates(top / "packages" / "api")
    assert "`git config core.hooksPath tools/githooks`" in finding.text


def test_husky_s_hooks_path_over_a_committed_gate_names_husky_s_own_file(tmp_path, monkeypatch):
    _isolated_git(tmp_path, monkeypatch)
    root = tmp_path / "repo"
    (root / "githooks").mkdir(parents=True)
    (root / ".husky" / "_").mkdir(parents=True)
    _git(root, "init", "-q")
    (root / "githooks" / "pre-commit").write_text(ROUTE_1, encoding="utf-8")
    (root / ".husky" / "pre-commit").write_text("npm test\n", encoding="utf-8")
    (root / ".husky" / "_" / "pre-commit").write_text('. "$(dirname "$0")/h"\n', encoding="utf-8")
    _git(root, "add", "githooks/pre-commit", ".husky/pre-commit")
    _git(root, "config", "core.hooksPath", ".husky/_")

    (finding,) = admin._doctor_silent_gates(root)
    assert "core.hooksPath (local config: .husky/_) sends git to .husky/_/pre-commit" in finding.text
    assert finding.text.endswith("or call crapkit hook-precommit from .husky/pre-commit")

    (root / ".husky" / "pre-commit").write_text("npm test\npython -m crapkit hook-precommit\n",
                                                encoding="utf-8")
    assert admin._doctor_silent_gates(root) == []


def test_a_pre_commit_config_naming_the_gate_before_pre_commit_install_is_named(repo):
    (repo / ".git" / "hooks" / "pre-commit").unlink()
    (repo / ".pre-commit-config.yaml").write_text(GATE_CONFIG, encoding="utf-8")

    (finding,) = admin._doctor_silent_gates(repo)
    assert finding.text.endswith("run `pre-commit install` in this repo")

    (repo / ".git" / "hooks" / "pre-commit").write_text(FRAMEWORK_HOOK, encoding="utf-8")
    assert admin._doctor_silent_gates(repo) == []
